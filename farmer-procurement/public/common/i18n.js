  window.__PH_LANGS = LANGS;

  /* =========================================================
     TRANSLATION ENGINE + LANGUAGE DROPDOWN
     - Text nodes + placeholder/title attributes only.
     - Original English cached per-node so switching back is lossless.
     - MutationObserver catches dynamically-injected DOM
       (navbar, footer, toasts, tables built by JS after load).
     ========================================================= */

  var STORE_KEY = 'ph_lang';
  var suspend = false;          // guard: our own DOM writes must not retrigger observer
  var observer = null;

  function getLang() {
    try { return localStorage.getItem(STORE_KEY) || 'en'; }
    catch (e) { return 'en'; }
  }
  function setLang(code) {
    try { localStorage.setItem(STORE_KEY, code); } catch (e) {}
  }

  // Return translated string, or null when it should stay English
  // (English selected, unknown language, or no exact match).
  function translate(en) {
    var lang = getLang();
    if (lang === 'en') return null;
    var dict = LANGS[lang];
    if (!dict) return null;
    var key = en.trim();
    if (Object.prototype.hasOwnProperty.call(dict, key)) {
      var val = dict[key];
      // preserve leading/trailing whitespace of the original node text
      return en.replace(key, val);
    }
    return null;
  }

  function procTextNode(node) {
    var raw = node.nodeValue;
    if (raw == null) return;
    // Cache the original English exactly once.
    if (node._i18nEn === undefined) {
      if (!raw.trim()) return;      // skip pure whitespace nodes
      node._i18nEn = raw;
    }
    var en = node._i18nEn;
    var lang = getLang();
    if (lang === 'en') {
      if (node.nodeValue !== en) node.nodeValue = en;   // restore
      return;
    }
    var t = translate(en);
    var want = (t != null) ? t : en;
    if (node.nodeValue !== want) node.nodeValue = want;
  }

  function procAttr(el) {
    ['placeholder', 'title'].forEach(function (attr) {
      if (!el.hasAttribute || !el.hasAttribute(attr)) return;
      var cacheKey = attr === 'placeholder' ? '_i18nPh' : '_i18nTitle';
      if (el[cacheKey] === undefined) {
        var cur = el.getAttribute(attr);
        if (!cur || !cur.trim()) return;
        el[cacheKey] = cur;
      }
      var en = el[cacheKey];
      var lang = getLang();
      if (lang === 'en') {
        if (el.getAttribute(attr) !== en) el.setAttribute(attr, en);
        return;
      }
      var t = translate(en);
      var want = (t != null) ? t : en;
      if (el.getAttribute(attr) !== want) el.setAttribute(attr, want);
    });
  }

  function walk(root) {
    if (!root) return;
    suspend = true;
    try {
      // Text nodes
      var tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode: function (n) {
          var p = n.parentNode;
          if (!p) return NodeFilter.FILTER_REJECT;
          var tag = p.nodeName;
          if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT') {
            return NodeFilter.FILTER_REJECT;
          }
          return NodeFilter.FILTER_ACCEPT;
        }
      });
      var n;
      while ((n = tw.nextNode())) procTextNode(n);

      // placeholder / title attributes
      if (root.querySelectorAll) {
        var els = root.querySelectorAll('[placeholder],[title]');
        for (var i = 0; i < els.length; i++) procAttr(els[i]);
        if (root.nodeType === 1 && (root.hasAttribute && (root.hasAttribute('placeholder') || root.hasAttribute('title')))) {
          procAttr(root);
        }
      }
    } finally {
      suspend = false;
    }
  }

  function startObserver() {
    if (observer) return;
    observer = new MutationObserver(function (muts) {
      if (suspend) return;
      for (var i = 0; i < muts.length; i++) {
        var m = muts[i];
        if (m.type === 'childList') {
          for (var j = 0; j < m.addedNodes.length; j++) {
            var an = m.addedNodes[j];
            if (an.nodeType === 3) { procTextNode(an); }
            else if (an.nodeType === 1) { walk(an); }
          }
        } else if (m.type === 'characterData') {
          if (m.target && m.target.nodeType === 3) procTextNode(m.target);
        } else if (m.type === 'attributes' && m.target && m.target.nodeType === 1) {
          procAttr(m.target);
        }
      }
    });
    observer.observe(document.documentElement, {
      childList: true, subtree: true, characterData: true,
      attributes: true, attributeFilter: ['placeholder', 'title']
    });
  }

  function buildControl() {
    if (document.getElementById('ph-lang-toggle')) return;
    var wrap = document.createElement('div');
    wrap.id = 'ph-lang-toggle';
    wrap.setAttribute('style', [
      'position:fixed', 'bottom:16px', 'left:16px', 'z-index:9999',
      'background:#15803d', 'color:#fff', 'padding:6px 8px',
      'border-radius:8px', 'box-shadow:0 2px 8px rgba(0,0,0,.25)',
      'font-family:system-ui,Arial,sans-serif', 'font-size:14px',
      'display:flex', 'align-items:center', 'gap:6px'
    ].join(';'));

    var label = document.createElement('span');
    label.textContent = '🌐';
    label.setAttribute('style', 'font-size:15px;line-height:1;');

    var sel = document.createElement('select');
    sel.setAttribute('style', [
      'background:#fff', 'color:#111', 'border:none', 'border-radius:5px',
      'padding:3px 6px', 'font-size:13px', 'cursor:pointer', 'outline:none'
    ].join(';'));

    Object.keys(LANG_NAMES).forEach(function (code) {
      var opt = document.createElement('option');
      opt.value = code;
      opt.textContent = LANG_NAMES[code];
      sel.appendChild(opt);
    });
    sel.value = getLang();

    sel.addEventListener('change', function () {
      setLang(sel.value);
      walk(document.body);
    });

    wrap.appendChild(label);
    wrap.appendChild(sel);
    // Mark control's own text so the observer/walk never rewrites it.
    suspend = true;
    document.body.appendChild(wrap);
    suspend = false;
  }

  function init() {
    buildControl();
    walk(document.body);
    startObserver();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
